func TestAdd_Concurrent(t *testing.T) {
	rc, bk := newFakeRC(""), &fakeBackup{}
	svc := newTestService(rc, bk)

	const n = 20
	var (
		wg sync.WaitGroup
		ok atomic.Int32
	)
	for i := range n {
		wg.Add(1)
		go func() {
			defer wg.Done()
			err := svc.Add(bg, fmt.Sprintf("10.0.0.%d", i+1))
			switch {
			case err == nil:
				ok.Add(1)
			case errors.Is(err, ErrLimitReached):
			default:
				t.Errorf("unexpected error: %v", err)
			}
		}()
	}
	wg.Wait()

	got := mustList(t, svc)
	if len(got) != MaxNameservers || int(ok.Load()) != MaxNameservers {
		t.Fatalf("list = %v, successes = %d, want exactly %d", got, ok.Load(), MaxNameservers)
	}
	seen := map[string]bool{}
	for _, a := range got {
		if seen[a] {
			t.Fatalf("duplicate %s in %v", a, got)
		}
		seen[a] = true
	}
	if !slices.Equal(bk.last(), got) {
		t.Fatalf("backup %v != list %v", bk.last(), got)
	}
	if rev := svc.State().Revision; rev != MaxNameservers {
		t.Fatalf("revision = %d, want %d", rev, MaxNameservers)
	}
}


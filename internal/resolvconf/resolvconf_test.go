func TestSetNameservers(t *testing.T) {
	tests := []struct {
		name string
		in   string
		set  []string
		want string
	}{
		{"replaces in place",
			"search lan\nnameserver 1.1.1.1\noptions ndots:2\n",
			[]string{"8.8.8.8", "9.9.9.9"},
			"search lan\nnameserver 8.8.8.8\nnameserver 9.9.9.9\noptions ndots:2\n"},
		{"collapses scattered lines to first position",
			"nameserver 1.1.1.1\nsearch lan\nnameserver 2.2.2.2\n",
			[]string{"3.3.3.3"},
			"nameserver 3.3.3.3\nsearch lan\n"},
		{"appends when there were none",
			"search lan\n", []string{"8.8.8.8"},
			"search lan\nnameserver 8.8.8.8\n"},
		{"empty list removes all",
			"nameserver 1.1.1.1\nsearch lan\nnameserver 2.2.2.2\n", nil,
			"search lan\n"},
		{"into empty file", "", []string{"1.1.1.1"}, "nameserver 1.1.1.1\n"},
		{"empty into empty", "", nil, ""},
		{"keeps comments",
			"# Generated by dhclient\nnameserver 1.1.1.1\n", []string{"8.8.8.8"},
			"# Generated by dhclient\nnameserver 8.8.8.8\n"},
		{"keeps invalid nameserver lines",
			"nameserver abc\nnameserver 1.1.1.1\n", []string{"2.2.2.2"},
			"nameserver abc\nnameserver 2.2.2.2\n"},
		{"ipv6 is normalized", "", []string{"2001:DB8::1"}, "nameserver 2001:db8::1\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			f := Parse([]byte(tt.in))
			f.SetNameservers(mustAddrs(tt.set...))
			if got := string(f.Render()); got != tt.want {
				t.Fatalf("got:\n%q\nwant:\n%q", got, tt.want)
			}
			if got := nsStrings(f); len(tt.set) > 0 && len(got) != len(tt.set) {
				t.Fatalf("Nameservers() = %v, want %d items", got, len(tt.set))
			}
		})
	}
}


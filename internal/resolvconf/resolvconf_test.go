func mustAddrs(ss ...string) []netip.Addr {
	res := make([]netip.Addr, len(ss))
	for i, s := range ss {
		res[i] = netip.MustParseAddr(s)
	}
	return res
}

func nsStrings(f *File) []string {
	var res []string
	for _, a := range f.Nameservers() {
		res = append(res, a.String())
	}
	return res
}

func dirNames(t *testing.T, dir string) []string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, e := range entries {
		names = append(names, e.Name())
	}
	return names
}

func TestParse_Nameservers(t *testing.T) {
	tests := []struct {
		name string
		in   string
		want []string
	}{
		{"empty", "", nil},
		{"only newlines", "\n\n", nil},
		{"single", "nameserver 8.8.8.8\n", []string{"8.8.8.8"}},
		{"ipv6", "nameserver 2001:4860:4860::8888\n", []string{"2001:4860:4860::8888"}},
		{"order kept", "nameserver 1.1.1.1\nnameserver 8.8.8.8\n", []string{"1.1.1.1", "8.8.8.8"}},
		{"comments and blanks", "# c\n\nnameserver 1.1.1.1\n; x\n", []string{"1.1.1.1"}},
		{"extra spaces and tabs", "nameserver\t  9.9.9.9  \n", []string{"9.9.9.9"}},
		{"trailing comment", "nameserver 8.8.4.4 # google\n", []string{"8.8.4.4"}},
		{"invalid ignored", "nameserver abc\nnameserver 1.1.1.1\n", []string{"1.1.1.1"}},
		{"missing address", "nameserver\nnameserver 1.1.1.1\n", []string{"1.1.1.1"}},
		{"no trailing newline", "nameserver 8.8.8.8", []string{"8.8.8.8"}},
		{"crlf", "nameserver 8.8.8.8\r\n", []string{"8.8.8.8"}},
		{"other directives ignored", "search lan\noptions ndots:2\ndomain x\n", nil},
		{"keyword is case sensitive", "NAMESERVER 1.1.1.1\n", nil},
		{"duplicates are kept as is", "nameserver 1.1.1.1\nnameserver 1.1.1.1\n", []string{"1.1.1.1", "1.1.1.1"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := nsStrings(Parse([]byte(tt.in)))
			if !slices.Equal(got, tt.want) {
				t.Fatalf("got %v, want %v", got, tt.want)
			}
		})
	}
}

func TestRender_RoundTrip(t *testing.T) {
	inputs := []string{
		"nameserver 8.8.8.8\n",
		"# Generated by dhclient\nsearch lan\nnameserver 1.1.1.1\noptions ndots:2\n",
		"nameserver abc\nnameserver 1.1.1.1\n",
		"\n# blank line above\nnameserver 2001:db8::1\n",
		"search   lan   example.com\nnameserver\t8.8.8.8\n",
	}
	for _, in := range inputs {
		if got := string(Parse([]byte(in)).Render()); got != in {
			t.Errorf("round trip changed file:\n got: %q\nwant: %q", got, in)
		}
	}
}


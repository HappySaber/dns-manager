func TestStore_WriteReplacesAndLeavesNoTempFiles(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	s := NewStore(path)

	for _, content := range []string{"nameserver 1.1.1.1\n", "nameserver 2.2.2.2\n", "nameserver 3.3.3.3\n"} {
		if err := s.Write(Parse([]byte(content))); err != nil {
			t.Fatal(err)
		}
	}
	data, _ := os.ReadFile(path)
	if string(data) != "nameserver 3.3.3.3\n" {
		t.Fatalf("file = %q", data)
	}
	if names := dirNames(t, dir); !slices.Equal(names, []string{"resolv.conf"}) {
		t.Fatalf("unexpected files in dir: %v", names)
	}
}

func TestStore_WritePermissions(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	if err := NewStore(path).Write(Parse([]byte("nameserver 1.1.1.1\n"))); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o644 {
		t.Fatalf("perm = %v, want 0644", info.Mode().Perm())
	}
}

func TestStore_ModifyKeepsOtherLines(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")
	orig := "# Generated by dhclient\nsearch lan\nnameserver 1.1.1.1\noptions ndots:2\n"
	if err := os.WriteFile(path, []byte(orig), 0o644); err != nil {
		t.Fatal(err)
	}
	s := NewStore(path)
	f, err := s.Read()
	if err != nil {
		t.Fatal(err)
	}
	f.SetNameservers(mustAddrs("8.8.8.8"))
	if err := s.Write(f); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(path)
	want := "# Generated by dhclient\nsearch lan\nnameserver 8.8.8.8\noptions ndots:2\n"
	if string(data) != want {
		t.Fatalf("got %q, want %q", data, want)
	}
}

func TestStore_ReadSeesExternalReplacement(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	s := NewStore(path)
	if err := s.Write(Parse([]byte("nameserver 1.1.1.1\n"))); err != nil {
		t.Fatal(err)
	}

	tmp := path + ".new"
	if err := os.WriteFile(tmp, []byte("nameserver 10.0.0.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Rename(tmp, path); err != nil {
		t.Fatal(err)
	}

	f, err := s.Read()
	if err != nil {
		t.Fatal(err)
	}
	if got := nsStrings(f); !slices.Equal(got, []string{"10.0.0.1"}) {
		t.Fatalf("got %v, want [10.0.0.1]", got)
	}
}

func FuzzParse(f *testing.F) {
	for _, seed := range []string{
		"", "nameserver 8.8.8.8\n", "search lan\r\nnameserver ::1", "nameserver", "\n\n#x\n", "\x00\xff",
	} {
		f.Add([]byte(seed))
	}
	f.Fuzz(func(t *testing.T, data []byte) {
		file := Parse(data)
		out := file.Render()
		again := Parse(out)
		if string(again.Render()) != string(out) {
			t.Fatalf("render is not stable:\n first: %q\nsecond: %q", out, again.Render())
		}
		if !slices.Equal(file.Nameservers(), again.Nameservers()) {
			t.Fatalf("nameservers changed after re-parse: %v vs %v", file.Nameservers(), again.Nameservers())
		}
	})
}
